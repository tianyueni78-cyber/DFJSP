function combined = run_stage_br_combination_selection(searchScenario)
%RUN_STAGE_BR_COMBINATION_SELECTION Reuse one completed Stage B-R search.
%   The complete search is not rerun. A deterministic linked right-shift
%   candidate is rebuilt from the exact same baseline and fault settings.

if nargin < 1 || ...
        ~isfield(searchScenario, 'complete_reschedule_search')
    error('run_stage_br_combination_selection:MissingSearch', ...
        'A scenario containing complete_reschedule_search is required.');
end

projectRoot = fileparts(fileparts(mfilename('fullpath')));
originalPath = path;
cleanupPath = onCleanup(@() path(originalPath));
addpath(fullfile(projectRoot, 'configs'));
addpath(fullfile(projectRoot, 'scripts'));
addpath(fullfile(projectRoot, 'src', 'evaluation'));
addpath(fullfile(projectRoot, 'src', 'rescheduling'));

rightScenario = run_stage_br_agv_linked_right_shift( ...
    searchScenario.baseline);
validate_same_scenario(searchScenario, rightScenario);

combined = rightScenario;
combined.complete_reschedule_search = ...
    searchScenario.complete_reschedule_search;
combined.combination_config = stage_br_combination_config();
combined.combined_selection = select_stage_br_combined_strategy( ...
    combined.baseline, combined.state, ...
    combined.linked_right_shift, ...
    combined.complete_reschedule_search, ...
    combined.combination_config);
combined.step = 11;
combined.is_combination_evaluated = true;
combined.is_validated = combined.is_validated && ...
    combined.combined_selection.is_validated;
end

function validate_same_scenario(searchScenario, rightScenario)
required = {'baseline', 'fault', 'restart_plan'};
for index = 1:numel(required)
    if ~isfield(searchScenario, required{index})
        error('run_stage_br_combination_selection:MissingField', ...
            'searchScenario.%s is required.', required{index});
    end
end

sameChromosome = isequal( ...
    searchScenario.baseline.chrom, rightScenario.baseline.chrom);
sameMakespan = abs(searchScenario.baseline.makespan - ...
    rightScenario.baseline.makespan) <= 1e-9;
sameFault = searchScenario.fault.machine_id == ...
    rightScenario.fault.machine_id && ...
    abs(searchScenario.fault.start_time - ...
    rightScenario.fault.start_time) <= 1e-9 && ...
    abs(searchScenario.fault.repair_end_time - ...
    rightScenario.fault.repair_end_time) <= 1e-9;
left = searchScenario.restart_plan;
right = rightScenario.restart_plan;
sameInterruptedOperation = left.job == right.job && ...
    left.operation == right.operation && ...
    left.machine_id == right.machine_id && ...
    strcmp(left.rule, right.rule) && ...
    left.restart_from_zero && right.restart_from_zero && ...
    ~left.progress_preserved && ~right.progress_preserved && ...
    abs(left.lost_processing_time - ...
    right.lost_processing_time) <= 1e-9 && ...
    abs(left.revised_completion_time - ...
    right.revised_completion_time) <= 1e-9;
if ~sameChromosome || ~sameMakespan || ~sameFault || ...
        ~sameInterruptedOperation
    error('run_stage_br_combination_selection:ScenarioMismatch', ...
        ['Complete search and right shift must share one baseline, ', ...
        'fault, and interrupted operation.']);
end
end

